// Tests inventory permissions, stock movements, alerts, and branch scoping.
import { randomUUID } from "node:crypto";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import request from "supertest";

import app from "../src/app.js";
import { prisma } from "../src/config/prisma.js";

const TEST_PASSWORD = "SteakzTest!2026";

const accounts = {
  hq: "hqmanager@test.steakz.com",
  admin: "admin@test.steakz.com",
  branchManager: "bmanager.london@test.steakz.com",
  server: "server.london@test.steakz.com",
};

async function login(email: string) {
  const response = await request(app)
    .post("/api/v1/auth/login")
    .send({ email, password: TEST_PASSWORD });

  expect(response.status).toBe(200);
  return response.body.data.accessToken as string;
}

describe("Inventory API", () => {
  let hqToken: string;
  let adminToken: string;
  let branchManagerToken: string;
  let serverToken: string;

  let londonBranchId: string;
  let manchesterBranchId: string;
  let ingredientId: string;
  let ingredientName: string;
  let branchManagerId: string;
  const stocktakeIds: string[] = [];

  beforeAll(async () => {
    // Load seeded test branches and authenticate test users.
    const [london, manchester] = await Promise.all([
      prisma.branch.findUnique({ where: { branchCode: "LON001" } }),
      prisma.branch.findUnique({ where: { branchCode: "MAN001" } }),
    ]);

    if (!london || !manchester) {
      throw new Error("Test branches are missing. Run the test seed first.");
    }

    const branchManager = await prisma.user.findUniqueOrThrow({
      where: { email: accounts.branchManager },
      select: { id: true },
    });

    branchManagerId = branchManager.id;
    londonBranchId = london.id;
    manchesterBranchId = manchester.id;

    [hqToken, adminToken, branchManagerToken, serverToken] =
      await Promise.all([
        login(accounts.hq),
        login(accounts.admin),
        login(accounts.branchManager),
        login(accounts.server),
      ]);

    // Create a unique ingredient through the API to isolate this test run.
    ingredientName = `Automated Test Ingredient ${randomUUID()}`;
    const response = await request(app)
      .post("/api/v1/inventory/ingredients")
      .set("Authorization", `Bearer ${hqToken}`)
      .send({ name: ingredientName, unit: "KG" });

    if (response.status !== 201) {
      throw new Error(
        `Could not create test ingredient: ${JSON.stringify(response.body)}`,
      );
    }

    ingredientId = response.body.data.id as string;
  });

  afterAll(async () => {
    // Collect audit-log entity IDs before removing the related test records.
    const auditEntities: Array<{ entityType: string; entityId: string }> = [];

    if (stocktakeIds.length) {
      const stocktakeItems = await prisma.stocktakeItem.findMany({
        where: { stocktakeId: { in: stocktakeIds } },
        select: { id: true },
      });

      auditEntities.push(
        ...stocktakeIds.map((id) => ({ entityType: "Stocktake", entityId: id })),
        ...stocktakeItems.map((item) => ({ entityType: "StocktakeItem", entityId: item.id })),
      );
    }

    if (ingredientId) {
      const inventoryTransactions = await prisma.inventoryTransaction.findMany({
        where: { ingredientId },
        select: { id: true },
      });
      auditEntities.push(
        ...inventoryTransactions.map((transaction) => ({
          entityType: "InventoryTransaction",
          entityId: transaction.id,
        })),
      );
    }

    // Remove audit entries generated by this test before deleting their entities.
    if (auditEntities.length) {
      await prisma.auditLog.deleteMany({ where: { OR: auditEntities } });
    }

    // Remove stocktake records created by this test before cleaning its ingredient.
    if (stocktakeIds.length) {
      await prisma.inventoryTransaction.deleteMany({ where: { stocktakeId: { in: stocktakeIds } } });
      await prisma.stocktakeItem.deleteMany({ where: { stocktakeId: { in: stocktakeIds } } });
      await prisma.stocktake.deleteMany({ where: { id: { in: stocktakeIds } } });
    }

    // Remove notifications generated for this test's unique ingredient.
    if (branchManagerId && londonBranchId && ingredientName) {
      await prisma.notification.deleteMany({
        where: {
          userId: branchManagerId,
          branchId: londonBranchId,
          type: { in: ["LOW_STOCK", "OUT_OF_STOCK"] },
          message: { contains: ingredientName },
        },
      });
    }

    // Remove only records created for this test ingredient.
    if (!ingredientId) return;
    await prisma.$transaction([
      prisma.inventoryAlert.deleteMany({ where: { ingredientId } }),
      prisma.inventoryTransaction.deleteMany({ where: { ingredientId } }),
      prisma.branchInventory.deleteMany({ where: { ingredientId } }),
      prisma.ingredient.deleteMany({ where: { id: ingredientId } }),
    ]);
  });

  it("allows the Headquarters Manager to create an ingredient", async () => {
    const ingredient = await prisma.ingredient.findUnique({
      where: { id: ingredientId },
    });

    expect(ingredient).not.toBeNull();
    expect(ingredient?.name).toBe(ingredientName);
    expect(ingredient?.unit).toBe("KG");
  });

  it("prevents Admin from viewing or creating ingredients", async () => {
    const listResponse = await request(app)
      .get("/api/v1/inventory/ingredients")
      .set("Authorization", `Bearer ${adminToken}`);

    expect(listResponse.status).toBe(403);

    const createResponse = await request(app)
      .post("/api/v1/inventory/ingredients")
      .set("Authorization", `Bearer ${adminToken}`)
      .send({ name: `Admin Forbidden ${randomUUID()}`, unit: "KG" });

    expect(createResponse.status).toBe(403);
  });

  it("prevents Servers from recording incoming stock", async () => {
    const response = await request(app)
      .post(`/api/v1/inventory/branches/${londonBranchId}/receiving`)
      .set("Authorization", `Bearer ${serverToken}`)
      .send({ ingredientId, quantity: 5 });

    expect(response.status).toBe(403);
  });

  it("restricts a Branch Manager to their assigned branch", async () => {
    const response = await request(app)
      .get(`/api/v1/inventory/branches/${manchesterBranchId}`)
      .set("Authorization", `Bearer ${branchManagerToken}`);

    expect(response.status).toBe(200);
    expect(response.body.data.branch.id).toBe(londonBranchId);
    expect(response.body.data.branch.id).not.toBe(manchesterBranchId);
  });

  it("records incoming stock once when an idempotency key is reused", async () => {
    const idempotencyKey = `inventory-test-${randomUUID()}`;
    const body = {
      ingredientId,
      quantity: 10,
      supplierName: "Automated Test Supplier",
      unitCost: 2.5,
      idempotencyKey,
    };

    const firstResponse = await request(app)
      .post(`/api/v1/inventory/branches/${londonBranchId}/receiving`)
      .set("Authorization", `Bearer ${branchManagerToken}`)
      .send(body);

    const duplicateResponse = await request(app)
      .post(`/api/v1/inventory/branches/${londonBranchId}/receiving`)
      .set("Authorization", `Bearer ${branchManagerToken}`)
      .send(body);

    expect(firstResponse.status).toBe(201);
    expect(duplicateResponse.status).toBe(201);
    expect(duplicateResponse.body.data.id).toBe(firstResponse.body.data.id);

    const inventory = await prisma.branchInventory.findUnique({
      where: {
        branchId_ingredientId: {
          branchId: londonBranchId,
          ingredientId,
        },
      },
    });

    expect(Number(inventory?.quantityOnHand)).toBe(10);
  });

  it("creates, updates, and resolves low-stock alerts while blocking negative stock", async () => {
    const minimumResponse = await request(app)
      .patch(
        `/api/v1/inventory/branches/${londonBranchId}/items/${ingredientId}/minimum`,
      )
      .set("Authorization", `Bearer ${branchManagerToken}`)
      .send({ minimumStockLevel: 5 });

    expect(minimumResponse.status).toBe(200);

    const lowStockResponse = await request(app)
      .post(`/api/v1/inventory/branches/${londonBranchId}/adjustments`)
      .set("Authorization", `Bearer ${branchManagerToken}`)
      .send({
        ingredientId,
        quantityChange: -6,
        transactionType: "WASTAGE",
        reason: "Automated inventory test",
      });

    expect(lowStockResponse.status).toBe(201);

    // Confirm the Branch Manager receives the low-stock notification.
    const lowStockNotificationCount = await prisma.notification.count({
      where: {
        userId: branchManagerId,
        branchId: londonBranchId,
        type: "LOW_STOCK",
        message: { contains: ingredientName },
      },
    });

    expect(lowStockNotificationCount).toBe(1);

    let alertsResponse = await request(app)
      .get(`/api/v1/inventory/branches/${londonBranchId}/alerts`)
      .set("Authorization", `Bearer ${branchManagerToken}`);

    expect(alertsResponse.status).toBe(200);
    expect(alertsResponse.body.data).toHaveLength(1);
    expect(alertsResponse.body.data[0].alertType).toBe("LOW_STOCK");

    const outOfStockResponse = await request(app)
      .post(`/api/v1/inventory/branches/${londonBranchId}/adjustments`)
      .set("Authorization", `Bearer ${branchManagerToken}`)
      .send({
        ingredientId,
        quantityChange: -4,
        transactionType: "WASTAGE",
        reason: "Automated inventory test",
      });

    expect(outOfStockResponse.status).toBe(201);

    alertsResponse = await request(app)
      .get(`/api/v1/inventory/branches/${londonBranchId}/alerts`)
      .set("Authorization", `Bearer ${branchManagerToken}`);

    expect(alertsResponse.body.data).toHaveLength(1);
    expect(alertsResponse.body.data[0].alertType).toBe("OUT_OF_STOCK");

    const negativeStockResponse = await request(app)
      .post(`/api/v1/inventory/branches/${londonBranchId}/adjustments`)
      .set("Authorization", `Bearer ${branchManagerToken}`)
      .send({
        ingredientId,
        quantityChange: -1,
        transactionType: "CORRECTION_DECREASE",
        reason: "Must not create negative stock",
      });

    expect(negativeStockResponse.status).toBe(409);
    expect(negativeStockResponse.body.error.message).toContain(
      "negative inventory",
    );

    const restoreResponse = await request(app)
      .post(`/api/v1/inventory/branches/${londonBranchId}/receiving`)
      .set("Authorization", `Bearer ${branchManagerToken}`)
      .send({ ingredientId, quantity: 6 });

    expect(restoreResponse.status).toBe(201);

    alertsResponse = await request(app)
      .get(`/api/v1/inventory/branches/${londonBranchId}/alerts`)
      .set("Authorization", `Bearer ${branchManagerToken}`);

    expect(alertsResponse.body.data).toHaveLength(0);

    const allAlertsResponse = await request(app)
      .get(
        `/api/v1/inventory/branches/${londonBranchId}/alerts?includeResolved=true`,
      )
      .set("Authorization", `Bearer ${branchManagerToken}`);

    expect(allAlertsResponse.status).toBe(200);
    expect(allAlertsResponse.body.data).toHaveLength(1);
    expect(allAlertsResponse.body.data[0].resolvedAt).not.toBeNull();

    const inventory = await prisma.branchInventory.findUnique({
      where: {
        branchId_ingredientId: {
          branchId: londonBranchId,
          ingredientId,
        },
      },
    });

    expect(Number(inventory?.quantityOnHand)).toBe(6);
  });



  it("reconciles from the physical count time and preserves later stock movements", async () => {
    // Establish a known balance before starting the stocktake.
    const beforeStart = await request(app)
      .post(`/api/v1/inventory/branches/${londonBranchId}/receiving`)
      .set("Authorization", `Bearer ${branchManagerToken}`)
      .send({ ingredientId, quantity: 10, idempotencyKey: `stocktake-before-${randomUUID()}` });
    expect(beforeStart.status).toBe(201);

    const startResponse = await request(app)
      .post(`/api/v1/inventory/branches/${londonBranchId}/stocktakes`)
      .set("Authorization", `Bearer ${branchManagerToken}`);
    expect(startResponse.status).toBe(201);
    const stocktakeId = startResponse.body.data.id as string;
    stocktakeIds.push(stocktakeId);

    // Confirm starting a stocktake creates an audit record for its user and branch.
    const startAudit = await prisma.auditLog.findFirst({
      where: {
        userId: branchManagerId,
        branchId: londonBranchId,
        action: "STOCKTAKE_STARTED",
        entityType: "Stocktake",
        entityId: stocktakeId,
      },
    });
    expect(startAudit).not.toBeNull();
    expect(startAudit?.details).toMatchObject({ status: "IN_PROGRESS" });

    // Only one stocktake may be active for this branch.
    const duplicateStart = await request(app)
      .post(`/api/v1/inventory/branches/${londonBranchId}/stocktakes`)
      .set("Authorization", `Bearer ${branchManagerToken}`);
    expect(duplicateStart.status).toBe(409);

    // Completion is blocked until every ingredient has been counted.
    const earlyComplete = await request(app)
      .patch(`/api/v1/inventory/branches/${londonBranchId}/stocktakes/${stocktakeId}/complete`)
      .set("Authorization", `Bearer ${branchManagerToken}`);
    expect(earlyComplete.status).toBe(409);

    // A normal stock movement before the physical count changes the count-time baseline.
    const beforeCount = await request(app)
      .post(`/api/v1/inventory/branches/${londonBranchId}/adjustments`)
      .set("Authorization", `Bearer ${branchManagerToken}`)
      .send({
        ingredientId,
        quantityChange: -2,
        transactionType: "WASTAGE",
        reason: "Movement before physical count",
      });
    expect(beforeCount.status).toBe(201);

    const negativeCount = await request(app)
      .patch(`/api/v1/inventory/branches/${londonBranchId}/stocktakes/${stocktakeId}/items/${ingredientId}`)
      .set("Authorization", `Bearer ${branchManagerToken}`)
      .send({ actualQuantity: -1 });
    expect(negativeCount.status).toBe(400);

    // System quantity is 14 at count time; physical count is 12, so variance is -2.
    const countResponse = await request(app)
      .patch(`/api/v1/inventory/branches/${londonBranchId}/stocktakes/${stocktakeId}/items/${ingredientId}`)
      .set("Authorization", `Bearer ${branchManagerToken}`)
      .send({ actualQuantity: 12 });
    expect(countResponse.status).toBe(200);
    expect(Number(countResponse.body.data.systemQuantityAtCount)).toBe(14);
    expect(Number(countResponse.body.data.variance)).toBe(-2);
    expect(countResponse.body.data.countedAt).not.toBeNull();

    // Confirm saving a physical count records the acting user and count details.
    const countAudit = await prisma.auditLog.findFirst({
      where: {
        userId: branchManagerId,
        branchId: londonBranchId,
        action: "STOCKTAKE_COUNT_RECORDED",
        entityType: "StocktakeItem",
        entityId: countResponse.body.data.id,
      },
    });
    expect(countAudit).not.toBeNull();
    expect(countAudit?.details).toMatchObject({
      stocktakeId,
      ingredientId,
      actualQuantity: "12",
      systemQuantityAtCount: "14",
      variance: "-2",
    });

    // A receipt after the physical count must remain in the final balance.
    const afterCount = await request(app)
      .post(`/api/v1/inventory/branches/${londonBranchId}/receiving`)
      .set("Authorization", `Bearer ${branchManagerToken}`)
      .send({ ingredientId, quantity: 5, idempotencyKey: `stocktake-after-${randomUUID()}` });
    expect(afterCount.status).toBe(201);

    // Count the remaining ingredients at their current balances for this integration test.
    const stocktake = await prisma.stocktake.findUnique({
      where: { id: stocktakeId },
      include: { items: true },
    });
    expect(stocktake).not.toBeNull();
    for (const item of stocktake!.items) {
      if (item.ingredientId === ingredientId) continue;
      const inventory = await prisma.branchInventory.findUnique({
        where: { branchId_ingredientId: { branchId: londonBranchId, ingredientId: item.ingredientId } },
        select: { quantityOnHand: true },
      });
      const quantity = Number(inventory?.quantityOnHand ?? 0);
      await prisma.stocktakeItem.update({
        where: { id: item.id },
        data: { actualQuantity: quantity, variance: 0, countedAt: new Date() },
      });
    }

    const completeResponse = await request(app)
      .patch(`/api/v1/inventory/branches/${londonBranchId}/stocktakes/${stocktakeId}/complete`)
      .set("Authorization", `Bearer ${branchManagerToken}`);
    expect(completeResponse.status).toBe(200);
    expect(completeResponse.body.data.status).toBe("COMPLETED");

    // Confirm completing the stocktake creates its own audit record.
    const completionAudit = await prisma.auditLog.findFirst({
      where: {
        userId: branchManagerId,
        branchId: londonBranchId,
        action: "STOCKTAKE_COMPLETED",
        entityType: "Stocktake",
        entityId: stocktakeId,
      },
    });
    expect(completionAudit).not.toBeNull();
    expect(completionAudit?.details).toMatchObject({ status: "COMPLETED" });

    // Physical count 12 plus the later receipt of 5 gives a final balance of 17.
    const finalInventory = await prisma.branchInventory.findUnique({
      where: { branchId_ingredientId: { branchId: londonBranchId, ingredientId } },
    });
    expect(Number(finalInventory?.quantityOnHand)).toBe(17);

    const stocktakeAdjustments = await prisma.inventoryTransaction.findMany({
      where: { stocktakeId, ingredientId, transactionType: "STOCKTAKE_ADJUSTMENT" },
    });
    expect(stocktakeAdjustments).toHaveLength(1);
    expect(Number(stocktakeAdjustments[0].quantityChange)).toBe(-2);
    expect(Number(stocktakeAdjustments[0].previousQuantity)).toBe(19);
    expect(Number(stocktakeAdjustments[0].newQuantity)).toBe(17);

    // Repeating completion cannot apply the adjustment twice.
    const duplicateComplete = await request(app)
      .patch(`/api/v1/inventory/branches/${londonBranchId}/stocktakes/${stocktakeId}/complete`)
      .set("Authorization", `Bearer ${branchManagerToken}`);
    expect(duplicateComplete.status).toBe(409);
    const adjustmentCount = await prisma.inventoryTransaction.count({
      where: { stocktakeId, ingredientId, transactionType: "STOCKTAKE_ADJUSTMENT" },
    });
    expect(adjustmentCount).toBe(1);
  });

  it("rejects invalid incoming stock quantities", async () => {
    const response = await request(app)
      .post(`/api/v1/inventory/branches/${londonBranchId}/receiving`)
      .set("Authorization", `Bearer ${branchManagerToken}`)
      .send({ ingredientId, quantity: 0 });

    expect(response.status).toBe(400);
  });
});
